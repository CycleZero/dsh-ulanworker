/**
 * Real-mount smoke test: does every role actually compose in a live process?
 *
 * The offline checks drive the plugin against a stub context, so they cannot
 * see deployment facts — most importantly that `tools.restrict()` rejects a
 * `toolFilter` naming a tool the deployment does not have, which fails the
 * whole role at composition time. This script boots a real harness with the
 * plugin mounted, calls `role_smoke`, and requires one `OK` line per role.
 *
 * It runs against the `headless` profile because that is a one-shot process
 * with no server and its own stdout: the plugin is injected with
 * `--patch`, and the probe uses the `fork` backend because the headless
 * profile registers only that provider. Composition — including the
 * `toolFilter` validation this test exists for — is the same code path.
 *
 * Usage:
 *   node smoke.mjs            # fork backend (works on a stock headless profile)
 *   node smoke.mjs --json     # print the raw report instead of a table
 *
 * Exits non-zero when any role fails to compose.
 *
 * @module dsh-ulanworker/smoke
 */

import { mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { spawn } from 'node:child_process'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(fileURLToPath(import.meta.url))
const WORK_DIR = join(tmpdir(), 'dsh-ulanworker-smoke')
const PATCH_FILE = join(WORK_DIR, 'smoke.yml')
const REPORT_FILE = join(WORK_DIR, 'report.txt')
const PROVIDER = 'fork'
const TIMEOUT_MS = 300_000
const PROMPT = 'Call the role_smoke tool exactly once with no arguments, then reply with the single word DONE.'

const EXPECTED = ['atlas', 'explore', 'librarian', 'looker', 'metis', 'momus', 'oracle', 'plan']

rmSync(WORK_DIR, { recursive: true, force: true })
mkdirSync(WORK_DIR, { recursive: true })
writeFileSync(
  PATCH_FILE,
  `# Generated by smoke.mjs; inserts the probe and the plugin under test.
- insert:
    - id: ulanworker-smoke
      name: ${join(ROOT, 'smoke-probe.mjs')}
      config:
        provider: ${PROVIDER}
    - id: ulanworker-bundle
      name: ${join(ROOT, 'index.js')}
      config:
        provider: ${PROVIDER}
`,
)
writeFileSync(REPORT_FILE, '')

const output = await run(PROMPT)
let report = ''
try {
  report = readFileSync(REPORT_FILE, 'utf8')
} catch {
  report = ''
}
rmSync(WORK_DIR, { recursive: true, force: true })

const results = new Map()
for (const line of `${report}\n${output}`.split('\n')) {
  const match = /^\s*role ([a-z-]+): (OK|FAIL)\s*(.*)$/.exec(line)
  if (match !== null) results.set(match[1], { ok: match[2] === 'OK', detail: match[3] })
}

if (process.argv.includes('--json')) {
  console.log(output.trim())
} else {
  for (const name of EXPECTED) {
    const result = results.get(name)
    console.log(
      result === undefined
        ? `role ${name.padEnd(10)} NOT REPORTED`
        : `role ${name.padEnd(10)} ${result.ok ? 'OK' : 'FAIL'}  ${result.detail}`,
    )
  }
}

const failures = []
for (const name of EXPECTED) {
  const result = results.get(name)
  if (result === undefined) failures.push(`${name}: the probe never reported this role`)
  else if (!result.ok) failures.push(`${name}: ${result.detail}`)
}

if (failures.length > 0) {
  console.error(`\nFAIL: ${failures.length} of ${EXPECTED.length} roles did not compose`)
  for (const failure of failures) console.error(`  - ${failure}`)
  if (results.size === 0) console.error(`\n--- raw output ---\n${output.trim()}`)
  if (report === '') console.error('(the probe wrote no report file; the tool was probably never called)')
  process.exit(1)
}
console.log(`\nPASS: all ${EXPECTED.length} roles composed against the real subagent service`)

/**
 * Run one headless task and return its stdout.
 *
 * @param task - the task text handed to the agent.
 * @returns the process stdout, or a diagnostic string when it fails to run.
 */
function run(task) {
  return new Promise((resolve) => {
    const child = spawn('dsh', ['--profile', 'headless', '--patch', PATCH_FILE, task], {
      cwd: WORK_DIR,
      stdio: ['ignore', 'pipe', 'pipe'],
      // The probe writes its report here; the model's own reply is not trusted
      // to echo a result verbatim.
      env: { ...process.env, DSH_ULANWORKER_SMOKE_REPORT: REPORT_FILE },
    })
    let stdout = ''
    let stderr = ''
    child.stdout.on('data', (chunk) => {
      stdout += chunk
    })
    child.stderr.on('data', (chunk) => {
      stderr += chunk
    })
    const timer = setTimeout(() => {
      child.kill('SIGKILL')
    }, TIMEOUT_MS)
    child.on('close', (code) => {
      clearTimeout(timer)
      if (code !== 0) resolve(`${stdout}\n${stderr}\n(exit ${code})`)
      else resolve(stdout)
    })
  })
}
